@pytest.mark.parametrize("text,expected", [
    ("в Выборге сегодня",        "Выборгский район"),     # prepositional
    ("под Выборгом",             "Выборгский район"),     # instrumental
    ("из Гатчины",               "Гатчинский муниципальный округ"),  # genitive
    ("Гатчиной не нашёл",        "Гатчинский муниципальный округ"),  # instrumental
    ("в Кингисеппе",             "Кингисеппский район"),  # prepositional
    ("Тихвином проезжали",       "Тихвинский район"),     # instrumental
    ("Тосном до сих пор",        "Тосненский район"),
])
def test_city_inflections(text: str, expected: str) -> None:
    """Все морфологические формы городов матчатся."""
    assert expected in lo_districts(text)


# ──────────────────────────────────────────────────────────────────────
# Pattern coverage — все district keys должны хоть на что-то реагировать
# ──────────────────────────────────────────────────────────────────────

def test_all_districts_compile() -> None:
    """COMPILED словарь не пустой и каждая запись имеет patterns."""
    assert len(r.COMPILED) >= 25
    for name, meta in r.COMPILED.items():
        assert "kind" in meta
        assert "patterns" in meta
        assert len(meta["patterns"]) > 0, f"{name}: no patterns"


def test_kind_distribution() -> None:
    """Sanity: должно быть 17-18 district_lo, 5+ subject_ru, 7+ district_spb."""
    from collections import Counter
    kinds_count = Counter(meta["kind"] for meta in r.COMPILED.values())
    assert kinds_count["district_lo"] >= 17, kinds_count
    assert kinds_count["district_spb"] >= 7, kinds_count
    assert kinds_count["subject_ru"] >= 5, kinds_count


