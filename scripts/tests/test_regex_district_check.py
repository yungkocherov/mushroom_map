# ──────────────────────────────────────────────────────────────────────
# False-positive guards (regression suite)
# ──────────────────────────────────────────────────────────────────────

def test_pervomayskie_polyanki_not_vyborgsky() -> None:
    """«Первомайские полянки» в Лужском не должны цеплять Выборгский
    (Первомайск — узкая форма посёлка)."""
    text = "Первомайские полянки. 3 мая 2026, Лужский район"
    lo = lo_districts(text)
    assert "Лужский район" in lo
    assert "Выборгский район" not in lo


def test_pervomayskoye_does_match_vyborgsky() -> None:
    """Сам посёлок Первомайское в Выборгском всё ещё должен ловиться."""
    text = "Поехали в Первомайское, грибы"
    assert "Выборгский район" in lo_districts(text)


def test_kirov_zavod_does_not_match_kirovsky_lo() -> None:
    """«Кировский завод» (промзона СПб) не должен цеплять Кировский ЛО.
    Узкий паттерн `\\bкировск(?:а|у|е|ом)?\\b` ловит только город Кировск
    в падежных формах, не прилагательное."""
    text = "Прогулка возле Кировского завода"
    # «Кировского» — adjective with -ого suffix, не должно совпасть с
    # city форм-set [а|у|е|ом]
    assert "Кировский район" not in lo_districts(text)


def test_lomonosov_surname_not_lomonosovsky() -> None:
    """Фамилия «Ломоносов» — НЕ должна давать LO Ломоносовский.
    (В patterns пользователя Lomonosov как surname не добавляется.)"""
    text = "Автор статьи М.В. Ломоносов"
    # Конкретно «Ломоносов» — фамилия, без других маркеров (Копорье,
    # пос Ломоносов, и т.п.) → не должен LO-район дать.
    assert "Ломоносовский район" not in lo_districts(text)


# ──────────────────────────────────────────────────────────────────────
# Hashtag fix: \b# не работает в начале строки — паттерны переписаны
# на просто #. Регрессия: эти посты ДОЛЖНЫ матчиться.
# ──────────────────────────────────────────────────────────────────────

@pytest.mark.parametrize("hashtag", [
    "#Курортный",
    "#приморский",
    "#пушкинский",
    "#красногвардейский",
    "#колпинск",
    "#невский",
])
def test_hashtag_at_start_of_string_matches(hashtag: str) -> None:
    """Хэштег в начале строки (наиболее частая форма в VK-постах)."""
    hits = kinds(hashtag)
    assert "district_spb" in hits, f"hashtag {hashtag} not matched at SOL"


@pytest.mark.parametrize("hashtag", [
    "первая строка\n#Курортный",
    "текст #приморский тег",
    "#грибы #пушкинский @grib_spb",
])
def test_hashtag_after_space_or_newline_matches(hashtag: str) -> None:
    """Хэштег после пробела/новой строки."""
    hits = kinds(hashtag)
    assert "district_spb" in hits, f"text={hashtag!r}"


# ──────────────────────────────────────────────────────────────────────
# LO ambiguity — посты с 2+ ЛО-районами не получают unique match
# ──────────────────────────────────────────────────────────────────────

def test_ambiguous_two_lo_districts() -> None:
    """«Приозерско-Выборгский район» — на границе, 2 матча."""
    text = "Приозерско-Выборгский район (мы на границе)))"
    lo = lo_districts(text)
    assert {"Приозерский район", "Выборгский район"}.issubset(lo)


def test_ambiguous_via_pipeline_logic() -> None:
    """Pipeline `--write` пишет только unique LO match. Manual repro:
    если len(lo) > 1, район не назначается."""
    text = "Выборгский и Приозерский районы"
    lo = lo_districts(text)
    assert len(lo) >= 2, "ambiguous case sanity"


